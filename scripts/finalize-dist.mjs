#!/usr/bin/env node
/**
 * Post-`astro build` adjustments to dist/ (run by `npm run build`):
 *
 * 1. Locale 404: Astro's directory output writes `src/pages/en/404.astro` to
 *    dist/en/404/index.html. Workers static assets (`not_found_handling:
 *    "404-page"`) serve the nearest `404.html` walking up from the request
 *    path, so move it to dist/en/404.html.
 * 2. Early Hints: append `Link: rel=preload` rules for HTML routes to
 *    dist/_headers (copied from public/_headers by Astro). Cloudflare caches
 *    these Link headers and replays them as `103 Early Hints` (zone setting
 *    on) for extensionless URLs; browsers also act on the Link header of the
 *    200 response before parsing the HTML. Preloads: every stylesheet linked
 *    from ALL built pages (the layout CSS), plus the CJK display-font subset
 *    on zh-TW routes only (English pages never render it).
 *
 * 3. Unreferenced originals: content images are imported through a glob, so
 *    Astro emits the original file of every inline-only image into _astro/
 *    even though nothing links it. Delete _astro/*.{jpg,jpeg,png} whose
 *    filename appears in no built text file.
 *
 * Idempotent: the generated _headers block is delimited by markers and
 * replaced on re-run, never appended twice.
 */
import { existsSync } from 'node:fs';
import { readdir, readFile, rename, rm, stat, writeFile } from 'node:fs/promises';
import path from 'node:path';

const root = process.cwd();
// Optional argument: an alternative output directory (scratch builds).
const dist = path.resolve(process.argv[2] ?? path.join(root, 'dist'));
const BEGIN = '# >>> generated by scripts/finalize-dist.mjs (Early Hints) >>>';
const END = '# <<< generated by scripts/finalize-dist.mjs <<<';
const ZH_ROUTES = ['/', '/blog', '/blog/*', '/pages/*', '/tags', '/tags/*', '/projects'];
const EN_ROUTES = ['/en', '/en/*'];

if (!existsSync(dist)) {
  console.error(`finalize-dist: ${dist} not found; run astro build first.`);
  process.exit(1);
}

// 1. English 404 page.
const en404Dir = path.join(dist, 'en', '404');
if (existsSync(path.join(en404Dir, 'index.html'))) {
  await rename(path.join(en404Dir, 'index.html'), path.join(dist, 'en', '404.html'));
  await rm(en404Dir, { recursive: true, force: true });
}
if (!existsSync(path.join(dist, 'en', '404.html'))) {
  console.error('finalize-dist: dist/en/404.html is missing.');
  process.exit(1);
}

// 2. Early Hints.
async function htmlFiles(dir) {
  const out = [];
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    if (entry.name.startsWith('_')) continue; // _astro, _pagefind
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) out.push(...(await htmlFiles(full)));
    else if (entry.name.endsWith('.html')) out.push(full);
  }
  return out;
}

const pages = await htmlFiles(dist);
let shared = null;
for (const file of pages) {
  const html = await readFile(file, 'utf8');
  const sheets = new Set(
    [...html.matchAll(/<link\b[^>]*>/g)]
      .map(([tag]) => tag)
      .filter((tag) => /\brel="?stylesheet"?/.test(tag))
      .map((tag) => tag.match(/\bhref="?(\/_astro\/[^"\s>]+\.css)"?/)?.[1])
      .filter(Boolean)
  );
  shared = shared ? new Set([...shared].filter((href) => sheets.has(href))) : sheets;
}
const styles = [...(shared ?? [])];

let fonts = [];
const manifestPath = path.join(root, 'node_modules', '.cache', 'display-font', 'manifest.json');
if (existsSync(manifestPath)) {
  const manifest = JSON.parse(await readFile(manifestPath, 'utf8'));
  // Same criterion as the layout's <link rel=preload>: only files it preloads.
  const zhHome = await readFile(path.join(dist, 'index.html'), 'utf8');
  fonts = manifest.faces.map((face) => face.href).filter((href) => zhHome.includes(`href="${href}"`));
}

const styleLinks = styles.map((href) => `<${href}>; rel=preload; as=style`);
const fontLinks = fonts.map((href) => `<${href}>; rel=preload; as=font; type="font/woff2"; crossorigin`);
const block = [BEGIN];
if (styleLinks.length || fontLinks.length) {
  for (const route of ZH_ROUTES) {
    block.push(route, `  Link: ${[...styleLinks, ...fontLinks].join(', ')}`, '');
  }
}
if (styleLinks.length) {
  for (const route of EN_ROUTES) block.push(route, `  Link: ${styleLinks.join(', ')}`, '');
}
block.push(END);

const headersPath = path.join(dist, '_headers');
const existing = existsSync(headersPath) ? await readFile(headersPath, 'utf8') : '';
const start = existing.indexOf(BEGIN);
const end = existing.indexOf(END);
const base = start >= 0 && end > start
  ? existing.slice(0, start) + existing.slice(end + END.length)
  : existing;
await writeFile(headersPath, `${base.trimEnd()}\n\n${block.join('\n')}\n`);

// 3. Unreferenced original images.
async function textFiles(dir) {
  const out = [];
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) out.push(...(await textFiles(full)));
    else if (/\.(html|css|js|mjs|json|xml|txt|webmanifest)$|^_headers$|^_redirects$/.test(entry.name)) out.push(full);
  }
  return out;
}

const astroDir = path.join(dist, '_astro');
const originals = existsSync(astroDir)
  ? (await readdir(astroDir)).filter((name) => /\.(jpe?g|png)$/i.test(name))
  : [];
let removedCount = 0;
let removedBytes = 0;
if (originals.length) {
  const corpus = (await Promise.all((await textFiles(dist)).map((file) => readFile(file, 'utf8')))).join('\n');
  for (const name of originals) {
    if (corpus.includes(name)) continue;
    const file = path.join(astroDir, name);
    removedBytes += (await stat(file)).size;
    await rm(file);
    removedCount += 1;
  }
}

console.info(
  `finalize-dist: removed ${removedCount} unreferenced original image(s)` +
    ` (${(removedBytes / 1048576).toFixed(1)} MB) from _astro/.`
);
console.info(
  `finalize-dist: en/404.html in place; Early Hints for ${styles.length} stylesheet(s)` +
    ` and ${fonts.length} font(s) across ${pages.length} pages.`
);
