import path from 'node:path';
import { visit } from 'unist-util-visit';
import type { Root } from 'hast';
import { contentAssetPath } from './content-assets.ts';
import { contentAssetFile, contentAssetSize } from './content-asset-files.ts';
import { inlineImageSrcset } from './content-image-variants.ts';

const DEFAULT_WIDTH = 1200;
const DEFAULT_HEIGHT = 675;

/**
 * Rewrite markdown image paths to `/assets/...`, attach intrinsic
 * dimensions for CLS-safe layout, and mark images for lazy loading.
 */
export function rehypeOptimizeImages() {
  return (tree: Root) => {
    visit(tree, 'element', (node) => {
      if (node.tagName !== 'img' || !node.properties) return;
      if (typeof node.properties.src !== 'string') return;

      node.properties.src = contentAssetPath(node.properties.src);

      if (contentAssetFile(node.properties.src)) {
        const { width, height } = contentAssetSize(node.properties.src) ?? {
          width: DEFAULT_WIDTH,
          height: DEFAULT_HEIGHT,
        };
        node.properties.width = width;
        node.properties.height = height;
        // WebP variants pre-generated by sync-assets (see
        // content-image-variants.ts); `src` keeps the original so feeds and
        // GIF/unsupported images are unchanged.
        const srcset = inlineImageSrcset(
          node.properties.src,
          width,
          path.join(process.cwd(), 'public')
        );
        if (srcset && !node.properties.srcSet) node.properties.srcSet = srcset;
      } else if (!node.properties.width || !node.properties.height) {
        node.properties.width = DEFAULT_WIDTH;
        node.properties.height = DEFAULT_HEIGHT;
      }

      node.properties.loading = 'lazy';
      node.properties.decoding = 'async';
      // `sizes` pairs with the WebP `srcset` above (inert when absent).
      if (!node.properties.sizes) {
        // Responsive images narrower than the 800px column render at their
        // own width.
        const width = Number(node.properties.width);
        node.properties.sizes =
          node.properties.srcSet && width > 0 && width < 800
            ? `(max-width: 768px) min(100vw, ${width}px), ${width}px`
            : '(max-width: 768px) 100vw, (max-width: 1200px) 800px, 800px';
      }
    });
  };
}
